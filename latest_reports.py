from __future__ import annotations

import argparse
import json
import subprocess
from datetime import UTC, datetime
from pathlib import Path
from typing import Literal, TypedDict
from urllib.parse import quote

from products import PRODUCTS


class LatestReport(TypedDict):
    product: str
    type: Literal["file"]
    name: str
    path: str
    created_at: str
    size: int
    download_url: str


def parse_creation_time(value: str) -> datetime:
    timestamp = datetime.fromisoformat(value)
    if timestamp.utcoffset() is None:
        raise ValueError(f"Report creation time must include a time zone: {value}")
    return timestamp.astimezone(UTC)


def git_creation_times(root: Path) -> dict[str, datetime]:
    shallow = subprocess.run(
        ["git", "rev-parse", "--is-shallow-repository"],
        cwd=root, check=True, capture_output=True, text=True,
    )
    if shallow.stdout.strip() != "false":
        raise ValueError("Report indexing requires complete Git history (fetch-depth: 0).")
    history = subprocess.run(
        ["git", "log", "--format=%cI", "--name-only", "--diff-filter=A", "--", "output/pdf"],
        cwd=root, check=True, capture_output=True, text=True,
    )
    result: dict[str, datetime] = {}
    timestamp: datetime | None = None
    for line in history.stdout.splitlines():
        if not line:
            continue
        if line.startswith("output/pdf/"):
            if timestamp is None:
                raise ValueError(f"Missing Git creation timestamp for {line}")
            result[line] = min(result.get(line, timestamp), timestamp)
        else:
            timestamp = parse_creation_time(line)
    return result


def write_latest_reports(
    root: Path,
    repository: str,
    branch: str,
    new_pdf: Path | None = None,
    created_at: datetime | None = None,
) -> list[LatestReport]:
    root = root.resolve()
    index = root / "output" / "latest.json"
    previous: dict[str, datetime] = {}
    if index.exists():
        records = json.loads(index.read_text(encoding="utf-8"))
        if not isinstance(records, list):
            raise ValueError("The latest-report index must be a JSON array.")
        for record in records:
            previous[record["path"]] = parse_creation_time(record["created_at"])

    creation_times = git_creation_times(root)
    new_path = (root / new_pdf).resolve() if new_pdf is not None else None
    if new_path is not None and not new_path.is_file():
        raise FileNotFoundError(new_path)
    generated_at = parse_creation_time((created_at or datetime.now(UTC)).isoformat())
    reports: list[LatestReport] = []
    for product in PRODUCTS.values():
        candidates: list[LatestReport] = []
        for pdf in (root / "output" / "pdf").glob(f"{product.slug}-updates-*.pdf"):
            relative = pdf.relative_to(root).as_posix()
            recorded_times = [
                times[relative] for times in (creation_times, previous) if relative in times
            ]
            if recorded_times:
                first_created = min(recorded_times)
            elif pdf.resolve() == new_path:
                first_created = generated_at
            else:
                raise ValueError(f"No recorded creation time for {relative}")
            candidates.append({
                "product": product.slug,
                "type": "file",
                "name": pdf.name,
                "path": relative,
                "created_at": (
                    first_created.isoformat(timespec="microseconds").replace("+00:00", "Z")
                ),
                "size": pdf.stat().st_size,
                "download_url": (
                    f"https://raw.githubusercontent.com/{repository}/"
                    f"{quote(branch, safe='')}/{quote(relative, safe='/')}"
                ),
            })
        if not candidates:
            raise ValueError(f"No PDF reports found for {product.name}")
        reports.append(max(
            candidates,
            key=lambda report: (parse_creation_time(report["created_at"]), report["name"]),
        ))
    index.write_text(json.dumps(reports, indent=2) + "\n", encoding="utf-8")
    return reports


def main() -> None:
    parser = argparse.ArgumentParser(description="Index the newest PDF report for each product.")
    parser.add_argument("--repository", required=True, help="GitHub owner/repository")
    parser.add_argument("--branch", default="main")
    parser.add_argument("--pdf", type=Path, help="PDF just generated by this workflow")
    args = parser.parse_args()
    write_latest_reports(Path.cwd(), args.repository, args.branch, args.pdf)


if __name__ == "__main__":
    main()
